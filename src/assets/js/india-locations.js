/** Flat searchable labels: "City, State" */
export function getIndiaLocationOptions() {
  const options = [];
  for (const [state, cities] of Object.entries(INDIA_LOCATIONS)) {
    options.push(state);
    for (const city of cities) {
      options.push(`${city}, ${state}`);
    }
  }
  return options.sort((a, b) => a.localeCompare(b));
}
